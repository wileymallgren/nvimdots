-- Extra LaTeX highlight patterns that touch parser nodes (numbers, ^ _ & \\,
-- \begin / \end, environment names, prose inside \text{...}).
--
-- Node names differ between versions of the `latex` parser, and one bad
-- pattern in a query file breaks ALL latex highlighting. So each candidate
-- below is checked against the installed parser first, and only the ones it
-- accepts are written to a generated query file:
--
--   <config>/after/queries/latex/highlights.scm   (";; extends")
--
-- Rejected patterns are simply skipped. Run :LatexHlCheck to see what was kept.
-- The file is rewritten when the set changes; restart nvim to apply a change.

local M = {}

local PRIO = "(#set! priority 130)"

local candidates = {
  -- prose inside \text{...} in math
  { "prose inside \\text{...}", "((text_mode) @string " .. PRIO .. ")" },

  -- Numbers, but only inside math or an environment (tabular cells etc.), so
  -- plain prose like "Problem 2" is NOT coloured.
  {
    "numbers (math / environments only)",
    [[((word) @number
  (#lua-match? @number "^%d[%d.,]*$")
  (#has-ancestor? @number inline_formula displayed_equation math_environment generic_environment)
  ]] .. PRIO .. ")",
  },

  { "superscript marker ^", [["^" @punctuation.special]] },
  { "subscript marker _", [["_" @punctuation.special]] },

  -- \begin / \end keywords and the environment name
  { "\\begin keyword", [["\\begin" @keyword]] },
  { "\\end keyword", [["\\end" @keyword]] },
  { "environment name (begin, field form)", "(begin name: (curly_group_text (_) @type))" },
  { "environment name (end, field form)", "(end name: (curly_group_text (_) @type))" },
  { "environment name (begin)", "(begin (curly_group_text (_) @type))" },
  { "environment name (end)", "(end (curly_group_text (_) @type))" },

  -- Table cell separator `&`: the node name differs between parser versions, so
  -- try several. The plain-text forms match it by its text.
  { "alignment marker & (token)", [["&" @punctuation.special]] },
  { "alignment marker & (alignment_tab)", "(alignment_tab) @punctuation.special" },
  { "alignment marker & (ampersand)", "(ampersand) @punctuation.special" },
  {
    "alignment marker & (word)",
    [[((word) @punctuation.special (#eq? @punctuation.special "&") ]] .. PRIO .. ")",
  },
  {
    "alignment marker & (text)",
    [[((text) @punctuation.special (#eq? @punctuation.special "&") ]] .. PRIO .. ")",
  },
  {
    "alignment marker & (operator)",
    [[((operator) @punctuation.special (#eq? @punctuation.special "&") ]] .. PRIO .. ")",
  },

  -- line break \\
  { "line break \\\\", "(line_break) @punctuation.special" },
  {
    "line break \\\\ as a command",
    [[((command_name) @punctuation.special (#eq? @punctuation.special "\\\\") ]] .. PRIO .. ")",
  },
}

local function parser_ready()
  return pcall(vim.treesitter.query.parse, "latex", "(command_name) @x")
end

-- Generated into the config's after/ dir so it extends (";; extends") rather
-- than replaces nvim-treesitter's own latex queries.
local target = vim.fn.stdpath("config") .. "/after/queries/latex/highlights.scm"

-- Returns { kept, dropped, changed, path } or nil, reason
function M.build()
  if not parser_ready() then
    return nil, "latex parser is not installed (or not loadable) yet"
  end

  local kept, dropped = {}, {}
  for _, c in ipairs(candidates) do
    if pcall(vim.treesitter.query.parse, "latex", c[2]) then
      table.insert(kept, c)
    else
      table.insert(dropped, c[1])
    end
  end

  local lines = {
    ";; extends",
    ";; GENERATED by lua/config/latex-hl.lua - only patterns the installed latex parser accepts",
    "",
  }
  for _, c in ipairs(kept) do
    table.insert(lines, "; " .. c[1])
    for _, l in ipairs(vim.split(c[2], "\n", { plain = true })) do
      table.insert(lines, l)
    end
    table.insert(lines, "")
  end

  local old = vim.fn.filereadable(target) == 1 and vim.fn.readfile(target) or nil
  local changed = not (old and vim.deep_equal(old, lines))
  if changed then
    vim.fn.mkdir(vim.fn.fnamemodify(target, ":h"), "p")
    vim.fn.writefile(lines, target)
  end
  return { kept = kept, dropped = dropped, changed = changed, path = target }
end

function M.setup()
  local done = false
  vim.api.nvim_create_autocmd("FileType", {
    pattern = { "rmd", "quarto", "markdown", "tex", "latex", "plaintex" },
    callback = function()
      if done then
        return
      end
      vim.schedule(function()
        local r = M.build()
        if r then
          done = true
          if r.changed then
            vim.notify("LaTeX highlight patterns updated - restart nvim to apply", vim.log.levels.INFO)
          end
        end
      end)
    end,
  })

  vim.api.nvim_create_user_command("LatexHlCheck", function()
    local r, why = M.build()
    if not r then
      return vim.notify("LatexHlCheck: " .. why .. "\nTry :checkhealth nvim-treesitter", vim.log.levels.WARN)
    end
    local names = vim.tbl_map(function(c)
      return c[1]
    end, r.kept)
    vim.notify(
      table.concat({
        "latex parser: OK",
        "active node patterns: " .. (#names > 0 and table.concat(names, ", ") or "none"),
        "skipped (not in this parser): " .. (#r.dropped > 0 and table.concat(r.dropped, ", ") or "none"),
        "generated file: " .. r.path,
        r.changed and "file changed - restart nvim to apply" or "file up to date",
      }, "\n"),
      vim.log.levels.INFO
    )
  end, { desc = "Show which extra LaTeX highlight patterns are active" })
end

return M
